#!/usr/bin/env python3
"""Nested cross-validation for the late-fusion multimodal fever model.

This script is a publication-oriented refactor of the UME late-fusion analysis
notebook. It implements the study's two-stage stacking architecture using:

- structured/tabular encounter-level variables;
- precomputed Qwen clinical-note embeddings;
- precomputed Chronos-2 body-temperature embeddings;
- precomputed MedImageInsight CT embeddings; and
- optional structured concept variables.

For each fitted late-fusion model, one regularized logistic-regression base
learner is trained per modality using only encounters for which that modality is
available. Leakage-free out-of-fold base probabilities are then combined with
modality-availability indicators and passed to a TabPFN V2.5 second-stage
stacker. Final unimodal models are refitted on the complete fitting subset before
prediction.

Nested cross-validation is used for unbiased performance estimation and for
threshold derivation. Within each outer-training fold, inner-CV predictions are
generated by complete late-fusion models; operating thresholds are derived only
from those predictions and then applied unchanged to the held-out outer fold.
The outer fold is never used to train a base learner, the stacker, or a threshold.

Expected embedding format
-------------------------
Each frozen embedding modality is supplied as:

1. ``*.npy``: a 2-D array with shape ``(n_encounters, embedding_dim)``;
2. ``*.csv``: an index containing the encounter ID column and ``embedding_row``.

Example
-------
python late_fusion_nested_cv.py \
    --tabular-csv data/ume_adapted.csv \
    --output-dir results/late_fusion_nested_cv \
    --text-embeddings data/ume_note_embeddings.npy \
    --text-index data/ume_note_embedding_index.csv \
    --time-series-embeddings data/ume_body_temp_chronos2_embeddings.npy \
    --time-series-index data/ume_body_temp_chronos2_index.csv \
    --ct-embeddings data/ume_ct_medimageinsight_embeddings.npy \
    --ct-index data/ume_ct_medimageinsight_index.csv

Notes
-----
- The default stacker reproduces the notebook design: TabPFN V2.5 initialized
  through ``tabpfn_extensions.TabPFNClassifier.create_default_for_version``.
- Raw foundation-model inference is intentionally separated into the public
  feature-extraction scripts. This entry point consumes frozen embeddings only.
- A logistic stacker is exposed only as an optional diagnostic/reproducibility
  alternative; the study late-fusion configuration uses TabPFN.
"""

