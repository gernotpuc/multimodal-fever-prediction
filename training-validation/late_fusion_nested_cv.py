def validate_config(config: Config) -> None:
    if config.outer_folds < 2 or config.inner_folds < 2 or config.base_oof_folds < 2:
        raise ValueError("outer_folds, inner_folds, and base_oof_folds must all be >= 2.")
    if config.n_bootstraps < 0:
        raise ValueError("n_bootstraps must be >= 0.")
    if config.threshold_grid_size < 2:
        raise ValueError("threshold_grid_size must be >= 2.")
    if config.base_c <= 0 or config.stacker_c <= 0:
        raise ValueError("base_c and stacker_c must be > 0.")
    if not 0 <= config.min_sensitivity <= 1 or not 0 <= config.min_specificity <= 1:
        raise ValueError("Sensitivity/specificity targets must be between 0 and 1.")
    pairs = [
        ("text", config.text_embeddings, config.text_index),
        ("time_series", config.time_series_embeddings, config.time_series_index),
        ("ct_image", config.ct_embeddings, config.ct_index),
    ]
    for name, emb, idx in pairs:
        if emb is None or idx is None:
            raise ValueError(f"{name}: both embedding and index files are required for the study model.")

