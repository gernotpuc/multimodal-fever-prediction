class ConstantProbabilityClassifier:
    """Fallback classifier for a modality/fold with insufficient usable data."""

    def __init__(self, probability: float):
        self.probability = float(np.clip(probability, 1e-6, 1.0 - 1e-6))
        self.classes_ = np.array([0, 1])

    def fit(self, X: np.ndarray, y: np.ndarray | None = None) -> "ConstantProbabilityClassifier":
        del X, y
        return self

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        p1 = np.full(np.asarray(X).shape[0], self.probability, dtype=float)
        return np.column_stack([1.0 - p1, p1])


