def make_late_fusion_arrays_for_fold(
    fit_df: pd.DataFrame,
    eval_df: pd.DataFrame,
    config: Config,
    embedding_sources: Mapping[str, EmbeddingSource],
) -> dict[str, object]:
    """Fit fold-specific preprocessing and construct modality matrices/masks."""
    fit_df = fit_df.copy().reset_index(drop=True)
    eval_df = eval_df.copy().reset_index(drop=True)
    fit_df[config.id_col] = fit_df[config.id_col].map(normalize_encounter_reference)
    eval_df[config.id_col] = eval_df[config.id_col].map(normalize_encounter_reference)

    fit_features: dict[str, np.ndarray] = {}
    eval_features: dict[str, np.ndarray] = {}
    fit_masks: dict[str, np.ndarray] = {}
    eval_masks: dict[str, np.ndarray] = {}
    tabular_feature_cols: list[str] = []

    if config.use_tabular:
        tabular_feature_cols = get_feature_columns(
            fit_df, config.id_col, config.label_col, config.concept_cols, config.exclude_cols
        )
        if not tabular_feature_cols:
            raise ValueError("Tabular modality enabled but no tabular features remain.")
        eval_df = ensure_columns_exist(eval_df, tabular_feature_cols)
        preprocessor, _, _ = build_preprocessor(fit_df, tabular_feature_cols)
        fit_features["tabular"] = to_dense_float32(preprocessor.fit_transform(fit_df[tabular_feature_cols]))
        eval_features["tabular"] = to_dense_float32(preprocessor.transform(eval_df[tabular_feature_cols]))
        fit_masks["tabular"] = np.ones(len(fit_df), dtype=bool)
        eval_masks["tabular"] = np.ones(len(eval_df), dtype=bool)

    if config.concept_cols:
        missing = [c for c in config.concept_cols if c not in fit_df.columns]
        if missing:
            raise ValueError(f"Missing concept columns in fit data: {missing}")
        eval_df = ensure_columns_exist(eval_df, config.concept_cols)
        concept_preprocessor, _, _ = build_preprocessor(fit_df, config.concept_cols)
        fit_features["concepts"] = to_dense_float32(
            concept_preprocessor.fit_transform(fit_df[list(config.concept_cols)])
        )
        eval_features["concepts"] = to_dense_float32(
            concept_preprocessor.transform(eval_df[list(config.concept_cols)])
        )
        fit_masks["concepts"] = np.ones(len(fit_df), dtype=bool)
        eval_masks["concepts"] = np.ones(len(eval_df), dtype=bool)

    for modality in ("text", "time_series", "ct_image"):
        source = embedding_sources[modality]
        x_fit, m_fit = lookup_matrix_for_ids(fit_df[config.id_col], source)
        x_eval, m_eval = lookup_matrix_for_ids(eval_df[config.id_col], source)
        fit_features[modality] = x_fit
        eval_features[modality] = x_eval
        fit_masks[modality] = m_fit
        eval_masks[modality] = m_eval

    modalities = [
        name for name in ("tabular", "text", "concepts", "time_series", "ct_image")
        if name in fit_features
    ]
    if not modalities:
        raise RuntimeError("No usable modality features found for late fusion.")

    return {
        "ids_fit": fit_df[config.id_col].astype(str).to_numpy(),
        "y_fit": fit_df[config.label_col].astype(int).to_numpy(),
        "features_fit": fit_features, "masks_fit": fit_masks,
        "ids_eval": eval_df[config.id_col].astype(str).to_numpy(),
        "y_eval": eval_df[config.label_col].astype(int).to_numpy(),
        "features_eval": eval_features, "masks_eval": eval_masks,
        "modalities": modalities, "tabular_feature_cols": tabular_feature_cols,
    }


def safe_prevalence(y: np.ndarray) -> float:
    y = np.asarray(y, dtype=float)
    if y.size == 0:
        return 0.5
    return float(np.clip(np.mean(y), 1e-6, 1.0 - 1e-6))


def make_unimodal_estimator(config: Config) -> Pipeline:
    """Regularized logistic base learner used independently for each modality."""
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("clf", LogisticRegression(
            C=config.base_c, penalty="l2", solver="lbfgs",
            max_iter=config.base_max_iter, class_weight=config.class_weight,
            random_state=config.random_state,
        )),
    ])


def fit_unimodal_model(
    X: np.ndarray | None, y: np.ndarray, has_mask: np.ndarray,
    modality_name: str, config: Config,
) -> tuple[object, float, str]:
    y = np.asarray(y, dtype=int)
    has_mask = np.asarray(has_mask, dtype=bool)
    if X is None:
        prevalence = safe_prevalence(y)
        return ConstantProbabilityClassifier(prevalence), prevalence, "missing_modality"

    n_usable = int(has_mask.sum())
    fallback = safe_prevalence(y[has_mask]) if n_usable else safe_prevalence(y)
    if n_usable < 10 or len(np.unique(y[has_mask])) < 2:
        LOGGER.warning(
            "Modality %s has insufficient usable training data (n=%d); using prevalence fallback.",
            modality_name, n_usable,
        )
        return ConstantProbabilityClassifier(fallback), fallback, "constant_fallback"

    model = make_unimodal_estimator(config)
    model.fit(np.asarray(X)[has_mask], y[has_mask])
    return model, fallback, "fitted"


def predict_unimodal_model(
    model: object, X: np.ndarray | None, has_mask: np.ndarray, fallback_prob: float
) -> np.ndarray:
    has_mask = np.asarray(has_mask, dtype=bool)
    if X is None:
        return np.full(len(has_mask), fallback_prob, dtype=float)
    X = np.asarray(X)
    probabilities = np.full(X.shape[0], fallback_prob, dtype=float)
    if has_mask.any():
        probabilities[has_mask] = model.predict_proba(X[has_mask])[:, 1]
    return np.clip(probabilities, 1e-6, 1.0 - 1e-6)


def make_tabpfn_classifier(config: Config) -> object:
    """Instantiate the notebook's versioned non-interactive TabPFN V2.5 stacker."""
    try:
        from tabpfn.constants import ModelVersion
        try:
            # Exact import path used in the study notebook.
            from tabpfn_extensions import TabPFNClassifier
        except (ImportError, AttributeError):
            # Compatibility path for current TabPFN releases; the pinned V2.5
            # model initialization below remains identical.
            from tabpfn import TabPFNClassifier
    except Exception as exc:
        raise ImportError(
            "The TabPFN stacker requires a compatible `tabpfn` installation. "
            "Install the repository dependencies before running the study configuration."
        ) from exc

    if not hasattr(ModelVersion, config.tabpfn_model_version):
        available = [name for name in dir(ModelVersion) if name.startswith("V")]
        raise ValueError(
            f"Requested TabPFN model version {config.tabpfn_model_version!r} is unavailable; "
            f"available versions: {available}"
        )

    version = getattr(ModelVersion, config.tabpfn_model_version)
    classifier = TabPFNClassifier.create_default_for_version(version)
    optional = {
        "device": resolve_tabpfn_device(config.tabpfn_device),
        "random_state": config.random_state,
        "ignore_pretraining_limits": config.tabpfn_ignore_pretraining_limits,
    }
    if hasattr(classifier, "set_params"):
        try:
            supported = set(classifier.get_params().keys()) if hasattr(classifier, "get_params") else set()
            params = {k: v for k, v in optional.items() if k in supported}
            if params:
                classifier.set_params(**params)
        except Exception as exc:
            LOGGER.warning("Could not set optional TabPFN parameters: %s", exc)
    return classifier


def make_stacking_estimator(config: Config) -> Pipeline:
    if config.stacker == "tabpfn":
        return Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("clf", make_tabpfn_classifier(config)),
        ])
    return Pipeline([
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler()),
        ("clf", LogisticRegression(
            C=config.stacker_c, penalty="l2", solver="lbfgs",
            max_iter=config.stacker_max_iter, class_weight=config.class_weight,
            random_state=config.random_state,
        )),
    ])


def build_meta_features(
    base_prob_df: pd.DataFrame, masks: Mapping[str, np.ndarray], modalities: Sequence[str]
) -> np.ndarray:
    blocks = [np.asarray(base_prob_df[f"p_{m}"], dtype=float).reshape(-1, 1) for m in modalities]
    blocks.extend(np.asarray(masks[m], dtype=float).reshape(-1, 1) for m in modalities)
    return np.hstack(blocks).astype(np.float32)


def effective_splits(y: np.ndarray, requested: int, context: str) -> int:
    y = np.asarray(y, dtype=int)
    counts = np.bincount(y, minlength=2)
    n_splits = min(int(requested), int(counts.min()))
    if n_splits < 2:
        raise RuntimeError(
            f"{context} requires at least two observations in each class; counts={counts.tolist()}."
        )
    return n_splits


def build_oof_unimodal_predictions(
    features: Mapping[str, np.ndarray], masks: Mapping[str, np.ndarray],
    y: np.ndarray, modalities: Sequence[str], config: Config, n_splits: int | None = None,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Generate leakage-free base probabilities used to train the stacker."""
    y = np.asarray(y, dtype=int)
    folds = effective_splits(y, n_splits or config.base_oof_folds, "Base-model OOF stacking")
    cv = StratifiedKFold(n_splits=folds, shuffle=True, random_state=config.random_state)
    out = pd.DataFrame(index=np.arange(len(y)))
    for modality in modalities:
        out[f"p_{modality}"] = np.nan
    info_rows: list[dict[str, object]] = []

    for fold_idx, (fit_idx, holdout_idx) in enumerate(cv.split(np.zeros(len(y)), y), start=1):
        for modality in modalities:
            X = features[modality]
            mask = masks[modality]
            model, fallback, status = fit_unimodal_model(
                X[fit_idx] if X is not None else None, y[fit_idx], mask[fit_idx], modality, config
            )
            out.loc[holdout_idx, f"p_{modality}"] = predict_unimodal_model(
                model, X[holdout_idx] if X is not None else None, mask[holdout_idx], fallback
            )
            info_rows.append({
                "fold": fold_idx, "modality": modality, "status": status,
                "n_fit": int(len(fit_idx)), "n_fit_available": int(mask[fit_idx].sum()),
                "fallback_probability": float(fallback),
            })

    if out.isna().any().any():
        raise RuntimeError("OOF base-probability table contains missing values.")
    return out, pd.DataFrame(info_rows)


def fit_final_unimodal_models(
    features: Mapping[str, np.ndarray], masks: Mapping[str, np.ndarray],
    y: np.ndarray, modalities: Sequence[str], config: Config,
) -> tuple[dict[str, dict[str, object]], pd.DataFrame]:
    fitted: dict[str, dict[str, object]] = {}
    rows = []
    for modality in modalities:
        model, fallback, status = fit_unimodal_model(
            features[modality], y, masks[modality], modality, config
        )
        fitted[modality] = {
            "model": model, "fallback_probability": fallback, "status": status
        }
        rows.append({
            "modality": modality, "status": status, "n_train": int(len(y)),
            "n_train_available": int(np.asarray(masks[modality]).sum()),
            "fallback_probability": float(fallback),
        })
    return fitted, pd.DataFrame(rows)


def predict_base_probabilities(
    fitted: Mapping[str, Mapping[str, object]], features: Mapping[str, np.ndarray],
    masks: Mapping[str, np.ndarray], modalities: Sequence[str],
) -> pd.DataFrame:
    n = len(next(iter(masks.values())))
    out = pd.DataFrame(index=np.arange(n))
    for modality in modalities:
        info = fitted[modality]
        out[f"p_{modality}"] = predict_unimodal_model(
            info["model"], features[modality], masks[modality],
            float(info["fallback_probability"]),
        )
    return out


def fit_late_fusion_package(
    features: Mapping[str, np.ndarray], masks: Mapping[str, np.ndarray], y: np.ndarray,
    modalities: Sequence[str], config: Config, n_splits: int | None = None,
) -> dict[str, object]:
    base_oof, oof_info = build_oof_unimodal_predictions(
        features, masks, y, modalities, config, n_splits
    )
    meta = build_meta_features(base_oof, masks, modalities)
    stacker = make_stacking_estimator(config)
    stacker.fit(meta, y)
    fitted_base, final_info = fit_final_unimodal_models(features, masks, y, modalities, config)
    return {
        "modalities": list(modalities), "stacker_model": stacker,
        "fitted_unimodal_models": fitted_base,
        "stacker_feature_names": [f"p_{m}" for m in modalities] + [f"has_{m}" for m in modalities],
        "oof_info_df": oof_info, "final_info_df": final_info,
    }


def predict_late_fusion_package(
    package: Mapping[str, object], features: Mapping[str, np.ndarray],
    masks: Mapping[str, np.ndarray],
) -> tuple[np.ndarray, pd.DataFrame]:
    modalities = list(package["modalities"])
    base = predict_base_probabilities(
        package["fitted_unimodal_models"], features, masks, modalities
    )
    meta = build_meta_features(base, masks, modalities)
    probabilities = package["stacker_model"].predict_proba(meta)[:, 1]
    return np.clip(probabilities, 1e-6, 1.0 - 1e-6), base


def make_inner_cv_predictions_for_thresholds(
    outer_train_df: pd.DataFrame, outer_fold: int, config: Config,
    embedding_sources: Mapping[str, EmbeddingSource],
) -> tuple[np.ndarray, np.ndarray, np.ndarray, pd.DataFrame]:
    y_outer = outer_train_df[config.label_col].astype(int).to_numpy()
    folds = effective_splits(y_outer, config.inner_folds, f"Inner CV in outer fold {outer_fold}")
    cv = StratifiedKFold(
        n_splits=folds, shuffle=True, random_state=config.random_state + 1000 + outer_fold
    )
    probabilities = np.full(len(outer_train_df), np.nan, dtype=float)
    ids = outer_train_df[config.id_col].map(normalize_encounter_reference).astype(str).to_numpy()
    info_frames: list[pd.DataFrame] = []

    for inner_fold, (fit_idx, val_idx) in enumerate(cv.split(outer_train_df, y_outer), start=1):
        arrays = make_late_fusion_arrays_for_fold(
            outer_train_df.iloc[fit_idx], outer_train_df.iloc[val_idx], config, embedding_sources
        )
        package = fit_late_fusion_package(
            arrays["features_fit"], arrays["masks_fit"], arrays["y_fit"],
            arrays["modalities"], config,
            n_splits=effective_splits(
                arrays["y_fit"], config.base_oof_folds,
                f"Base OOF in outer fold {outer_fold}, inner fold {inner_fold}"
            ),
        )
        probabilities[val_idx] = predict_late_fusion_package(
            package, arrays["features_eval"], arrays["masks_eval"]
        )[0]
        for key, stage in (("oof_info_df", "threshold_inner_cv_oof_base"),
                           ("final_info_df", "threshold_inner_cv_final_base")):
            frame = package[key].copy()
            frame.insert(0, "outer_fold", outer_fold)
            frame.insert(1, "inner_fold", inner_fold)
            frame.insert(2, "stage", stage)
            info_frames.append(frame)

    if np.isnan(probabilities).any():
        raise RuntimeError(f"Inner-CV predictions contain NaN in outer fold {outer_fold}.")
    return ids, y_outer, probabilities, pd.concat(info_frames, ignore_index=True)


def package_version(name: str) -> str | None:
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
        return None


def save_run_metadata(config: Config, embedding_sources: Mapping[str, EmbeddingSource]) -> None:
    config.output_dir.mkdir(parents=True, exist_ok=True)
    config_dict = asdict(config)
    for key, value in list(config_dict.items()):
        if isinstance(value, Path):
            config_dict[key] = str(value)
        elif isinstance(value, tuple):
            config_dict[key] = list(value)
    metadata = {
        "model": {
            "name": "nested_cv_late_fusion_tabpfn_v25",
            "architecture": "unimodal logistic base learners + probability/availability stacking",
            "stacker": config.stacker,
            "tabpfn_model_version": config.tabpfn_model_version if config.stacker == "tabpfn" else None,
        },
        "config": config_dict,
        "active_embedding_modalities": {
            name: {"n_embeddings": len(source.lookup), "dim": source.dim}
            for name, source in embedding_sources.items()
        },
        "software": {
            "python": sys.version.split()[0], "platform": platform.platform(),
            "numpy": np.__version__, "pandas": pd.__version__,
            "scikit_learn": sklearn.__version__,
            "tabpfn": package_version("tabpfn"),
            "tabpfn_extensions": package_version("tabpfn-extensions"),
        },
    }
    with (config.output_dir / "run_config.json").open("w", encoding="utf-8") as handle:
        json.dump(metadata, handle, indent=2)


def run_nested_cv(
    df: pd.DataFrame, config: Config, embedding_sources: Mapping[str, EmbeddingSource]
) -> None:
    y_all = df[config.label_col].astype(int).to_numpy()
    counts = np.bincount(y_all, minlength=2)
    if counts.min() < config.outer_folds:
        raise ValueError(
            f"outer_folds exceeds minority-class count: counts={counts.tolist()}, "
            f"outer_folds={config.outer_folds}."
        )
    outer_cv = StratifiedKFold(
        n_splits=config.outer_folds, shuffle=True, random_state=config.random_state
    )

    outer_predictions: list[pd.DataFrame] = []
    outer_point_rows: list[dict[str, object]] = []
    outer_bootstrap: list[pd.DataFrame] = []
    outer_confusions: list[pd.DataFrame] = []
    candidate_all: list[pd.DataFrame] = []
    grid_all: list[pd.DataFrame] = []
    youden_all: list[pd.DataFrame] = []
    inner_predictions: list[pd.DataFrame] = []
    training_info: list[pd.DataFrame] = []
    availability_rows: list[dict[str, object]] = []
    feature_info_rows: list[dict[str, object]] = []

    for outer_fold, (train_idx, test_idx) in enumerate(outer_cv.split(df, y_all), start=1):
        LOGGER.info(
            "Outer fold %d/%d: train=%d test=%d", outer_fold, config.outer_folds,
            len(train_idx), len(test_idx),
        )
        outer_train = df.iloc[train_idx].copy().reset_index(drop=True)
        outer_test = df.iloc[test_idx].copy().reset_index(drop=True)

        inner_ids, inner_y, inner_prob, inner_info = make_inner_cv_predictions_for_thresholds(
            outer_train, outer_fold, config, embedding_sources
        )
        training_info.append(inner_info)
        inner_predictions.append(pd.DataFrame({
            "outer_fold": outer_fold, config.id_col: inner_ids, "y_true": inner_y,
            "y_prob": inner_prob, "prediction_source": "inner_cv_threshold_derivation",
            "model": "nested_cv_late_fusion_tabpfn_v25", "stacker": config.stacker,
        }))

        candidates, grid, youden = build_candidate_thresholds(inner_y, inner_prob, config)
        for frame in (candidates, grid, youden):
            frame.insert(0, "outer_fold", outer_fold)
        candidate_all.append(candidates)
        grid_all.append(grid)
        youden_all.append(youden)

        arrays = make_late_fusion_arrays_for_fold(
            outer_train, outer_test, config, embedding_sources
        )
        modalities = list(arrays["modalities"])
        feature_info_rows.append({
            "outer_fold": outer_fold, "model": "nested_cv_late_fusion_tabpfn_v25",
            "stacker": config.stacker, "modalities": ",".join(modalities),
            "n_modalities": len(modalities),
            "stacker_feature_count": 2 * len(modalities),
            "tabular_input_columns": len(arrays["tabular_feature_cols"]),
        })

        for cohort_name, masks in (("outer_train", arrays["masks_fit"]),
                                   ("outer_test", arrays["masks_eval"])):
            for modality in modalities:
                mask = np.asarray(masks[modality], dtype=bool)
                availability_rows.append({
                    "outer_fold": outer_fold, "cohort": cohort_name, "modality": modality,
                    "n": int(len(mask)), "n_available": int(mask.sum()),
                    "availability": float(mask.mean()),
                })

        package = fit_late_fusion_package(
            arrays["features_fit"], arrays["masks_fit"], arrays["y_fit"], modalities, config,
            n_splits=effective_splits(
                arrays["y_fit"], config.base_oof_folds, f"Outer fold {outer_fold} base OOF"
            ),
        )
        for key, stage in (("oof_info_df", "outer_train_oof_base"),
                           ("final_info_df", "outer_train_final_base")):
            frame = package[key].copy()
            frame.insert(0, "outer_fold", outer_fold)
            frame.insert(1, "stage", stage)
            training_info.append(frame)

        y_prob, base_prob = predict_late_fusion_package(
            package, arrays["features_eval"], arrays["masks_eval"]
        )
        pred = pd.DataFrame({
            "outer_fold": outer_fold, config.id_col: arrays["ids_eval"],
            "y_true": arrays["y_eval"], "y_prob": y_prob,
        })
        for column in base_prob.columns:
            pred[column] = base_prob[column].to_numpy()
        for modality in modalities:
            pred[f"has_{modality}"] = np.asarray(arrays["masks_eval"][modality], dtype=int)

        for threshold_idx, row in enumerate(candidates.itertuples(index=False)):
            strategy = str(row.strategy)
            threshold = float(row.threshold)
            pred[f"threshold_{strategy}"] = threshold
            y_pred = (y_prob >= threshold).astype(int)
            pred[f"y_pred_{strategy}"] = y_pred

            point, summary = bootstrap_binary_metrics(
                arrays["y_eval"], y_prob, threshold, config.n_bootstraps,
                config.bootstrap_seed + outer_fold * 1000 + threshold_idx,
            )
            outer_point_rows.append({
                "outer_fold": outer_fold, "threshold_strategy": strategy,
                "threshold": threshold, **point,
            })
            summary = summary.copy()
            summary.insert(0, "outer_fold", outer_fold)
            summary.insert(1, "threshold_strategy", strategy)
            summary.insert(2, "threshold", threshold)
            outer_bootstrap.append(summary)
            outer_confusions.append(confusion_matrix_long(
                "outer_fold_test", strategy, threshold, arrays["y_eval"], y_pred, outer_fold
            ))
        outer_predictions.append(pred)

    predictions_df = pd.concat(outer_predictions, ignore_index=True)
    candidates_df = pd.concat(candidate_all, ignore_index=True)
    grid_df = pd.concat(grid_all, ignore_index=True)
    youden_df = pd.concat(youden_all, ignore_index=True) if youden_all else pd.DataFrame()
    inner_df = pd.concat(inner_predictions, ignore_index=True)
    training_df = pd.concat(training_info, ignore_index=True) if training_info else pd.DataFrame()
    point_df = pd.DataFrame(outer_point_rows)
    bootstrap_df = pd.concat(outer_bootstrap, ignore_index=True)
    confusion_df = pd.concat(outer_confusions, ignore_index=True)
    availability_df = pd.DataFrame(availability_rows)
    feature_info_df = pd.DataFrame(feature_info_rows)

    out = config.output_dir
    threshold_dir = out / "threshold_analysis"
    save_csv(availability_df, out / "nested_cv_late_fusion_modality_availability.csv")
    save_csv(feature_info_df, out / "nested_cv_late_fusion_feature_info.csv")
    save_csv(training_df, out / "nested_cv_late_fusion_training_info.csv")
    save_csv(inner_df, out / "nested_cv_inner_predictions_for_threshold_derivation.csv")
    save_csv(candidates_df, threshold_dir / "nested_cv_candidate_thresholds_all_outer_folds.csv")
    save_csv(grid_df, threshold_dir / "nested_cv_inner_threshold_grid_metrics_all_outer_folds.csv")
    save_csv(youden_df, threshold_dir / "nested_cv_inner_youden_thresholds_all_outer_folds.csv")
    save_csv(predictions_df, out / "nested_cv_outer_fold_predictions_late_fusion_tabpfn_v25.csv")
    save_csv(point_df, threshold_dir / "nested_cv_outer_fold_point_metrics_by_threshold.csv")
    save_csv(bootstrap_df, threshold_dir / "nested_cv_outer_fold_bootstrap_metrics_by_threshold_long.csv")
    save_csv(confusion_df, threshold_dir / "nested_cv_outer_fold_confusion_matrices_by_threshold_long.csv")

    pooled_point_rows = []
    pooled_bootstrap = []
    pooled_confusions = []
    for strategy in candidates_df["strategy"].drop_duplicates():
        pred_col = f"y_pred_{strategy}"
        threshold_col = f"threshold_{strategy}"
        if pred_col not in predictions_df:
            continue
        y_true = predictions_df["y_true"].astype(int).to_numpy()
        y_prob = predictions_df["y_prob"].astype(float).to_numpy()
        y_pred = predictions_df[pred_col].astype(int).to_numpy()
        thresholds = predictions_df[threshold_col].astype(float).to_numpy()
        point, summary = bootstrap_binary_metrics_from_predictions(
            y_true, y_prob, y_pred, config.n_bootstraps,
            config.bootstrap_seed + 90000 + len(pooled_point_rows),
        )
        pooled_point_rows.append({
            "threshold_strategy": strategy, "threshold_mean": float(thresholds.mean()),
            "threshold_sd": float(thresholds.std()), "threshold_min": float(thresholds.min()),
            "threshold_max": float(thresholds.max()), **point,
        })
        summary = summary.copy()
        summary.insert(0, "threshold_strategy", strategy)
        summary.insert(1, "threshold_mean", float(thresholds.mean()))
        summary.insert(2, "threshold_sd", float(thresholds.std()))
        pooled_bootstrap.append(summary)
        pooled_confusions.append(confusion_matrix_long(
            "pooled_outer_cv", strategy, float(thresholds.mean()), y_true, y_pred
        ))

    pooled_point_df = pd.DataFrame(pooled_point_rows)
    pooled_bootstrap_df = pd.concat(pooled_bootstrap, ignore_index=True)
    pooled_confusion_df = pd.concat(pooled_confusions, ignore_index=True)
    save_csv(pooled_point_df, threshold_dir / "nested_cv_pooled_outer_predictions_point_metrics_by_threshold.csv")
    save_csv(pooled_bootstrap_df, threshold_dir / "nested_cv_pooled_outer_predictions_bootstrap_metrics_by_threshold_long.csv")
    save_csv(pooled_confusion_df, threshold_dir / "nested_cv_pooled_outer_predictions_confusion_matrices_by_threshold_long.csv")

    selected = config.selected_threshold_strategy
    if selected not in set(pooled_point_df["threshold_strategy"]):
        LOGGER.warning("Threshold strategy %s unavailable; falling back to youden.", selected)
        selected = "youden"
    save_csv(
        pooled_point_df[pooled_point_df["threshold_strategy"] == selected].copy(),
        threshold_dir / f"nested_cv_selected_{selected}_pooled_point_metrics.csv",
    )
    save_csv(
        pooled_bootstrap_df[pooled_bootstrap_df["threshold_strategy"] == selected].copy(),
        threshold_dir / f"nested_cv_selected_{selected}_pooled_bootstrap_metrics_long.csv",
    )
    save_csv(
        pooled_confusion_df[pooled_confusion_df["threshold_strategy"] == selected].copy(),
        threshold_dir / f"nested_cv_selected_{selected}_pooled_confusion_matrix_long.csv",
    )
    LOGGER.info("Nested CV complete: %s", out)


def main(argv: Sequence[str] | None = None) -> int:
    setup_logging()
    config = parse_args(argv)
    set_global_seed(config.random_state)
    config.output_dir.mkdir(parents=True, exist_ok=True)
    df = load_tabular_data(config)
    embedding_sources = load_embedding_sources(config)
    expected = {"text", "time_series", "ct_image"}
    if set(embedding_sources) != expected:
        raise RuntimeError(f"Expected embedding modalities {sorted(expected)}; got {sorted(embedding_sources)}")
    for name, source in embedding_sources.items():
        overlap = df[config.id_col].isin(source.lookup).sum()
        LOGGER.info(
            "%s embedding overlap: %d/%d (%.1f%%)", name, overlap, len(df),
            100.0 * overlap / max(len(df), 1),
        )
    save_run_metadata(config, embedding_sources)
    run_nested_cv(df, config, embedding_sources)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
